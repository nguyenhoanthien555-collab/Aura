# The payload survives the transport
# ======================================================================

# Every one of these is a real thing a model puts in a `complete`
# message, and each breaks a different part of a hand-rolled serializer.
# All are *well formed* inner JSON - a newline inside the message is the
# two-character escape `\n`, which is the only spelling valid JSON has.
# The malformed variants live in their own group at the bottom.
#
# `pretty_printed` is the payload from the original report.
ACTIONS = [
    pytest.param('{"action": "home"}', "home", id="minimal"),
    pytest.param(
        '{"action": "complete", "message": "Done."}', "complete", id="complete"
    ),
    pytest.param(
        '{"action": "complete", "message": "Line one\\nLine two"}',
        "complete",
        id="escaped_newline_in_message",
    ),
    pytest.param(
        '{"action": "complete", "message": "I opened \\"Settings\\" for you"}',
        "complete",
        id="escaped_quotes_in_message",
    ),
    pytest.param(
        '{"action": "input_text", "text": "C:\\\\Users\\\\Ember"}',
        "input_text",
        id="backslashes",
    ),
    pytest.param(
        '{"action": "complete", "message": "Xong r\u1ed3i nh\u00e9, b\u1ea1n \u01a1i!"}',
        "complete",
        id="non_ascii",
    ),
    pytest.param(
        '{"action": "complete", "message": "nice {} work"}',
        "complete",
        id="braces_inside_a_string",
    ),
    pytest.param(
        '{\n  "action": "complete",\n  "message": "Hey. Good to see you, '
        'bro. What are we building today?"\n}',
        "complete",
        id="pretty_printed_the_reported_payload",
    ),
    pytest.param(
        '```json\n{"action": "complete", "message": "Fenced"}\n```',
        "complete",
        id="fenced_by_the_model",
    ),
]


@pytest.mark.parametrize("model_reply, expected_action", ACTIONS)
def test_the_action_reaches_the_client_byte_for_byte(
    client, says, model_reply, expected_action
):
    """
    The contract, stated once.

    Not "the reply parses" and not "the reply contains the action" -
    equality. Anything that rewrites the reply on the way out is a bug
    here even if the result happens to still be valid JSON, because the
    phone parses this string and a rewrite is a silent change of
    meaning.
    """

    assert reply_of(tick(client, model_reply, says)) == model_reply


@pytest.mark.parametrize("model_reply, expected_action", ACTIONS)
def test_the_delivered_action_is_itself_parseable(
    client, says, model_reply, expected_action
):
    """
    The half that matters to the phone.

    `AgentActionParser` strips fences and brace-matches before decoding,
    so this mirrors it: take what arrived, and check an action comes out
    with the name the model chose. A payload that survives transport but
    cannot be parsed would satisfy the test above and still break the
    agent.
    """

    delivered = reply_of(tick(client, model_reply, says))

    text = delivered.strip()

    if text.startswith("```"):
        text = text.split("\n", 1)[1].rsplit("```", 1)[0]

    action = json.loads(text[text.index("{"):text.rindex("}") + 1])

    assert action["action"] == expected_action


def test_an_escaped_newline_stays_a_two_character_escape(client, says):
    """
    The specific corruption a hand-rolled serializer produces.

    A newline inside a JSON string is spelled `\\n` - backslash, n. The
    outer document escapes that backslash again, so the wire carries
    `\\\\n` and the phone's decode of the *outer* document hands the
    parser back `\\n`, which its decode of the *inner* one turns into a
    real line break. Two layers, and a serializer that unescapes one
    layer too many delivers a literal 0x0A inside a quoted string, which
    is invalid JSON and would fail on the phone rather than here.
    """

    response = tick(
        client,
        '{"action": "complete", "message": "Line one\\nLine two"}',
        says,
    )

    assert b"\\\\n" in response.content

    delivered = reply_of(response)

    assert "\\n" in delivered
    assert "\n" not in delivered

    assert json.loads(delivered)["message"] == "Line one\nLine two"


def test_a_backslash_survives_as_one_backslash(client, says):
    """
    A Windows path is the case that shows a double-escape immediately:
    one round of over-escaping turns `C:\\Users` into `C:\\\\Users`, and
    the phone would type the wrong thing.
    """

    delivered = reply_of(
        tick(client, '{"action": "input_text", "text": "C:\\\\Users"}', says)
    )

    assert json.loads(delivered)["text"] == "C:\\Users"


def test_the_payload_is_not_truncated(client, says):
    """
    Check 10 from the report: a reply cut off before its closing brace.

    A long `complete` message is where a length cap would first bite, and
    a truncated object is exactly what `extractJsonObject` refuses - it
    scans for a balanced brace and returns null when it runs out of text.
    """

    message = "This is a sentence that repeats. " * 60

    model_reply = json.dumps({"action": "complete", "message": message})

    delivered = reply_of(tick(client, model_reply, says))

    assert delivered == model_reply
    assert delivered.endswith("}")
    assert json.loads(delivered)["message"] == message


def test_the_action_is_delivered_exactly_once(client, says):
    """
    Check 5: an action emitted twice.

    Two concatenated objects would leave `extractJsonObject` reading the
    first and silently discarding the second - or, worse, executing a
    stale action. One `reply`, one object.
    """

    delivered = reply_of(
        tick(client, '{"action": "complete", "message": "Once"}', says)
    )

    assert delivered.count('"action"') == 1

    payload = json.loads(client.post(
        "/api/chat",
        json={
            "session_id": "agent-protocol",
            "message": "tick",
            "context": AGENT_CONTEXT,
        },
    ).content)

    assert sorted(payload) == [
        "message_id", "metadata", "reply", "session_id"
    ]


def test_no_prose_is_mixed_into_the_action(client, says):
    """
    Check 7: the server mixing plain text and a JSON action.

    A machine turn skips styling, the identity anchor and the transcript
    (`brain/conversation.py`), so nothing may prepend a greeting or
    append a sign-off. If one did, the reply would still parse - the
    parser tolerates surrounding prose - but the *conversational* path
    would have leaked into a machine one, and that is how a persona ends
    up narrating device actions.
    """

    model_reply = '{"action": "click", "node_id": "node_1"}'

    delivered = reply_of(tick(client, model_reply, says))

    assert delivered == model_reply
    assert delivered.strip().startswith("{")
    assert delivered.strip().endswith("}")


