def test_a_normal_chat_turn_is_prose_not_an_action(client, says):
    """
    The turn the report was actually about.

    With no machine context the reply is styled and saved and is not
    expected to be JSON at all - so nothing on the phone should be
    parsing it as an action. This is the contrast that makes the routing
    bug visible: an action-shaped reply here would mean a conversational
    message had been sent down the agent path.
    """

    says("Hey. Good to see you, bro. What are we building today?")

    response = client.post(
        "/api/chat",
        json={"session_id": "prose", "message": "hello Auraaa"},
    )

    assert '"action"' not in reply_of(response)


@pytest.mark.parametrize(
    "model_reply, expected",
    [
        ("action", "action"),
        ("conversation", "conversation"),
        ("Action.", "action"),
        ("  ACTION  ", "action"),
        ("I think this is a conversation", "conversation"),
        ("", "conversation"),
        # The case that matters most here: a model that ignores the
        # one-word instruction and answers with an action object. The
        # word "action" is in it, so a naive reader routes an ordinary
        # greeting into the device loop.
        ('{"action": "complete", "message": "Hey!"}', "action"),
    ],
)
def test_an_intent_probe_is_normalised_to_one_word(
    client, says, model_reply, expected
):
    """
    The probe answers a routing question, and the phone compares two
    strings. Normalising on the server (`server/runtime.py`) is what
    keeps that rule in one place.

    The last case is not a bug being blessed - it is the documented
    behaviour of `read_intent`, which reads word sets, and it is worth
    pinning because it is the one input that can route a greeting into
    the agent loop. A model that answers the intent prompt with an
    action object is a prompt problem, not a transport one.
    """

    says(model_reply)

    response = client.post(
        "/api/chat",
        json={
            "session_id": "probe",
            "message": "hello Auraaa",
            "context": {"intent_probe": True},
        },
    )

    assert reply_of(response) == expected


def test_a_probe_reply_is_never_an_action_object(client, says):
    """
    Whatever the model said, what leaves the server is one of two words.
    An action object reaching the phone from a probe would be parsed as
    an action by a client that only asked how to route.
    """

    says('{\n  "action": "complete",\n  "message": "Hi there"\n}')

    response = client.post(
        "/api/chat",
        json={
            "session_id": "probe",
            "message": "hello Auraaa",
            "context": {"intent_probe": True},
        },
    )

    delivered = reply_of(response)

    assert delivered in {"action", "conversation"}
    assert "{" not in delivered


