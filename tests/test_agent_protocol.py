@pytest.fixture
def says(monkeypatch):
    """
    Make the provider return exactly one string.

    Patching the conversation's `llm` rather than the provider class, so
    the reply travels the real path from `ConversationManager` through
    the route's serializer - which is the half under test.
    """

    from server.runtime import get_runtime

    def fix(reply: str):
        conversation = get_runtime().engine.conversation

        class Fixed:
            provider_name = "mock"

            def generate(self, prompt: str) -> str:
                return reply

            def stream(self, prompt: str):
                yield reply

        monkeypatch.setattr(conversation, "llm", Fixed())

    return fix


def reply_of(response) -> str:
    """
    The `reply` field, decoded from the raw bytes.

    Goes through `json.loads(response.content)` rather than
    `response.json()` to make the decoding step explicit: what is being
    checked is that the bytes on the wire decode to the string the model
    produced, byte for byte.
    """

    assert response.status_code == 200, response.text

    return json.loads(response.content)["reply"]


def tick(client, reply_text, says):
    """One agent tick whose model reply is `reply_text`."""

    says(reply_text)

    return client.post(
        "/api/chat",
        json={
            "session_id": "agent-protocol",
            "message": "tick",
            "context": AGENT_CONTEXT,
        },
    )


