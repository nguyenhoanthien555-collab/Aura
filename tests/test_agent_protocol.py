@pytest.mark.parametrize(
    "model_reply",
    [
        pytest.param("Sure! I'll open that for you.", id="prose_only"),
        pytest.param(
            '{"action": "complete", "message": "cut off',
            id="truncated_object",
        ),
        pytest.param("{}", id="empty_object"),
        pytest.param("", id="empty_reply"),
        # A raw 0x0A inside a quoted string. Invalid JSON, and a model
        # does emit it - which is why it belongs here rather than with
        # the well-formed payloads above.
        pytest.param(
            '{"action": "complete", "message": "Line one\nLine two"}',
            id="literal_newline_inside_a_string",
        ),
    ],
)
def test_a_malformed_action_is_still_delivered_intact(
    client, says, model_reply
):
    """
    The server does not validate the model's JSON, and should not start.

    Every one of these is a reply the phone must decide about, and it has
    the context to do it: `AgentActionParser` returns a `Failure` whose
    reason is fed back as `last_action_error`, which is the model's only
    channel for correcting itself. A server that rejected these would
    turn a recoverable tick into a dead request, and a server that
    "repaired" them would send the phone an action nobody chose.

    So the contract is delivery, not judgement - including of an empty
    reply, which arrives as an empty string rather than a 500.
    """

    assert reply_of(tick(client, model_reply, says)) == model_reply


