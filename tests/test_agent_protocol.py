"""
The server -> Android response contract.

The Android accessibility agent reads the reply to a machine turn as
JSON: `{"action": "...", ...}`. That reply is generated by a model, and
it reaches the phone inside a *second* JSON document - the `reply` field
of `ChatResponse`. So there are two layers of escaping between what the
model wrote and what `AgentActionParser` parses, and a bug in the outer
one corrupts the inner one silently: the payload still parses as HTTP
JSON, and the damage only shows up as "the agent stopped working".

This file pins the outer layer. It asserts on `response.content` - the
actual bytes on the wire - rather than on `response.json()`, because
`.json()` is the very decoder whose input is in question, and a test
that round-trips through it would pass on a payload no other client
could read.

What is deliberately NOT tested here: whether a model emits well-formed
JSON. It often does not, which is why `AgentActionParser` tolerates
fences, prose and unknown fields (20 tests in
`android/app/src/test/.../AgentActionParserTest.kt`). The contract this
file defends is narrower and absolute - whatever the model wrote, the
transport delivers unchanged.

Written after a report of "Failed to parse action from server" on a
normal chat message. The cause turned out to be an installed APK older
than the server it was talking to; the transport was correct. These
tests are what makes that conclusion checkable rather than asserted, and
what would catch a real break of the same contract later.
"""

