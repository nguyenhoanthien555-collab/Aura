def test_streamed_chunks_concatenate_to_the_whole_reply(client, says):
    """
    Check 4. The chat screen accumulates `reply += event.text`, so the
    contract is that concatenating the chunks in index order reproduces
    the reply exactly - no chunk dropped, none duplicated, no separator
    introduced between them.
    """

    says("Hey. Good to see you, bro.")

    with client.websocket_connect(
        "/api/chat/stream?session_id=stream-protocol"
    ) as socket:

        socket.send_json({"message": "hello Auraaa"})

        assert socket.receive_json()["type"] == "started"

        chunks = []

        while True:
            frame = socket.receive_json()
            if frame["type"] != "chunk":
                break
            chunks.append(frame)

        assert frame["type"] == "complete", frame

    assert [c["index"] for c in chunks] == list(range(len(chunks)))

    assert "".join(c["chunk"] for c in chunks) == (
        "Hey. Good to see you, bro."
    )


def test_a_streamed_chunk_carries_its_text_unescaped_once(client, says):
    """
    Every frame is its own JSON document, so a newline inside a chunk is
    escaped by the frame and must decode back to one newline - not to a
    literal `\\n` the user would read as two characters on screen.
    """

    says("first line\nsecond line")

    with client.websocket_connect(
        "/api/chat/stream?session_id=stream-escape"
    ) as socket:

        socket.send_json({"message": "hi"})

        assert socket.receive_json()["type"] == "started"

        text = ""

        while True:
            frame = socket.receive_json()
            if frame["type"] != "chunk":
                break
            text += frame["chunk"]

        assert frame["type"] == "complete", frame

    assert text == "first line\nsecond line"
    assert "\\n" not in text


